  item.prefix = prefixCopy[family];
  item.dimensionText = splitDimensionCopy[item.id] || dimensionCopy[family];
  item.question = questionCopy[item.id];
  if (optionCopy[item.id]) {
    if (optionCopy[item.id].length !== item.options.length) throw new Error(`${item.id} 选项审阅数量不一致`);
    item.options.forEach((option, index) => { option.text = optionCopy[item.id][index]; });
  }
